function typeCard(name, what, who, strategy, prep, note) {
  return '<article class="card type-card"><h3>' + name + "</h3>" +
    '<div class="type-grid"><div><h4>무엇을 보나</h4><p>' + what + "</p></div><div><h4>이런 학생에게 유리</h4><p>" + who + "</p></div></div>" +
    "<h4>전략</h4><ul class=\"plain\">" + strategy.map(function (s) { return "<li>" + s + "</li>"; }).join("") + "</ul>" +
    "<h4>학년별 준비</h4><ul class=\"steps\">" + prep.map(function (p) { return "<li><b>" + p[0] + "</b> " + p[1] + "</li>"; }).join("") + "</ul>" +
    (note ? '<p class="muted small">※ ' + note + "</p>" : "") + "</article>";
}
